"""Build the MBON / GVS archive name tables.

PS4 MBON (CUSA15006) and PS4 GVS (CUSA08379) store every archive as
``archives/XX/XXXXXXXX.bin`` with no file names. Both titles reuse the VS2-era
path hashes for their shared global tables (for example ``0xDFD38C70`` is
``012list/character_list`` in VS2, Over Boost, GVS and the MBON PS4 port), and
GVS reuses them for unit, effect, GUI and sound packs as well. MBON keeps the
older FHM asset hashes for its own data; descatal's BoostStudio
(https://github.com/descatal/BoostStudio) documents the common ones in
``ExvsCommonAssets``.

This tool joins:

* ``src/assets/fhm2d-name-map.generated.json`` (this project's VS2 / OB name map),
* the local archive catalogs of the owner's game dumps (``catalog-archives.tsv``,
  one row per archive; kept under the gitignored ``tmp/`` tree), and
* BoostStudio's ``ExvsCommonAssets`` hashes (MBON only, credited below),

and writes one TSV per game that lists only hashes present in that game:

    hash  route  name  group  source  title

``group`` is set for the curated "data init" items (global tables and shared
packs, the PS4 counterpart of the Over Boost FHM2D Init list) and empty for
plain naming rows. No game data is copied: the tables hold hashes and names
only.

Usage:
    python tools/build_ps4_name_tables.py
    python tools/build_ps4_name_tables.py --mbon-catalog <tsv> --gvs-catalog <tsv>
"""

