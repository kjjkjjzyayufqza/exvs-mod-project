def load_catalog(path: Path) -> set[int]:
    hashes: set[int] = set()
    with path.open(encoding="utf-8") as handle:
        header = handle.readline().rstrip("\n").split("\t")
        column = header.index("relative_path")
        for line in handle:
            parts = line.rstrip("\n").split("\t")
            if len(parts) <= column:
                continue
            stem = parts[column].replace("\\", "/").rsplit("/", 1)[-1].split(".", 1)[0].split("__", 1)[0]
            try:
                hashes.add(int(stem, 16))
            except ValueError:
                continue
    return hashes


def load_name_map(path: Path) -> dict[int, dict]:
    with path.open(encoding="utf-8") as handle:
        document = json.load(handle)
    out: dict[int, dict] = {}
    for entry in document["entries"]:
        confidence = entry.get("confidence")
        if confidence not in SOURCE_LABELS:
            continue
        out[int(entry["hashName"], 16)] = entry
    return out


def clean(text: str) -> str:
    return text.replace("\t", " ").replace("\n", " ").strip()


def rows_for(
    hashes: set[int],
    names: dict[int, dict],
    init: dict[int, tuple[str, str]],
    extra: list[tuple[int, str, str, str, str, str]],
) -> list[tuple[str, str, str, str, str, str]]:
    rows: dict[int, tuple[str, str, str, str, str, str]] = {}
    for value, route, name, group, source, title in extra:
        rows[value] = (f"{value:08X}", route, name, group, source, title)
    for value in sorted(hashes):
        if value in rows or value not in names:
            continue
        entry = names[value]
        route = clean(entry.get("routePrefix") or "")
        name = clean(entry["name"])
        group, title = init.get(value, ("", ""))
        rows[value] = (f"{value:08X}", route, name, group, SOURCE_LABELS[entry["confidence"]], title)
    return sorted(rows.values(), key=lambda row: (row[3] == "", row[1], row[2], row[0]))


def write(path: Path, game: str, extra_credit: str, rows: list[tuple[str, ...]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = "".join("\t".join(row) + "\n" for row in rows)
    path.write_text(HEADER.format(game=game, extra=extra_credit) + body, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name-map", type=Path, default=NAME_MAP)
    parser.add_argument("--mbon-catalog", type=Path, default=MBON_CATALOG)
    parser.add_argument("--gvs-catalog", type=Path, default=GVS_CATALOG)
    args = parser.parse_args()

    for path in (args.name_map, args.mbon_catalog, args.gvs_catalog):
        if not path.is_file():
            print(f"missing input: {path}", file=sys.stderr)
            return 2

    names = load_name_map(args.name_map)
    mbon_hashes = load_catalog(args.mbon_catalog)
    gvs_hashes = load_catalog(args.gvs_catalog)

    # BoostStudio assets stay listed even when the base dump lacks them: the
    # game references them (SCharacterList), so updates / DLC can ship them.
    boost = [(value, "common", name, "boost_studio", "boost-studio", title) for value, name, title in BOOST_STUDIO_COMMON]
    mbon_rows = rows_for(mbon_hashes, names, {**SHARED_INIT, **MBON_INIT}, boost)
    gvs_rows = rows_for(gvs_hashes, names, {**SHARED_INIT, **GVS_INIT}, [])

    write(MBON_OUT, "PS4 MBON (CUSA15006)", "; common FHM assets: descatal / BoostStudio (https://github.com/descatal/BoostStudio)", mbon_rows)
    write(GVS_OUT, "PS4 GVS (CUSA08379)", "", gvs_rows)
    for label, rows in (("mbon", mbon_rows), ("gvs", gvs_rows)):
        init_count = sum(1 for row in rows if row[3])
        print(f"{label}: {len(rows)} names, {init_count} init items")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
