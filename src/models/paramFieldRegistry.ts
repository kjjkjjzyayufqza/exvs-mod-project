const lookupCache = new Map<string, Map<number, ParamFieldMeta>>()

function getLookupMap(fileType: string): Map<number, ParamFieldMeta> {
  let map = lookupCache.get(fileType)
  if (map) return map
  map = new Map()
  const fields = REGISTRY[fileType]
  if (fields) {
    for (const field of fields) {
      map.set(field.hash, field)
    }
  }
  lookupCache.set(fileType, map)
  return map
}

export function getFieldMeta(fileType: string, hash: number): ParamFieldMeta | undefined {
  return getLookupMap(fileType).get(hash)
}

export function getAllFieldMeta(fileType: string): ParamFieldMeta[] {
  return REGISTRY[fileType] ?? []
}

export function getFieldGroups(fileType: string): string[] {
  const fields = REGISTRY[fileType]
  if (!fields) return []
  const seen = new Set<string>()
  const ordered: string[] = []
  for (const field of fields) {
    if (!seen.has(field.group)) {
      seen.add(field.group)
      ordered.push(field.group)
    }
  }
  return ordered
}

export function hasRegistry(fileType: string): boolean {
  return fileType in REGISTRY
}
